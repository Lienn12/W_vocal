CREATE TABLE IF NOT EXISTS worlds (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  topic VARCHAR(120) NOT NULL DEFAULT '',
  description VARCHAR(500) NOT NULL DEFAULT '',
  emoji VARCHAR(16) NOT NULL DEFAULT '🌍',
  color VARCHAR(9) NOT NULL DEFAULT '#6366f1',
  category VARCHAR(60) NOT NULL DEFAULT '',
  level VARCHAR(8) NOT NULL DEFAULT '',
  status ENUM('draft','published') NOT NULL DEFAULT 'draft',
  sort_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) CHARACTER SET utf8mb4;

CREATE TABLE IF NOT EXISTS vocabulary (
  id INT AUTO_INCREMENT PRIMARY KEY,
  world_id INT NOT NULL,
  word VARCHAR(80) NOT NULL,
  pronunciation VARCHAR(80) NOT NULL DEFAULT '',
  part_of_speech VARCHAR(30) NOT NULL DEFAULT '',
  meaning VARCHAR(300) NOT NULL,
  example VARCHAR(300) NOT NULL DEFAULT '',
  UNIQUE KEY uq_world_word (world_id, word),
  FOREIGN KEY (world_id) REFERENCES worlds(id) ON DELETE CASCADE
) CHARACTER SET utf8mb4;

CREATE TABLE IF NOT EXISTS scenes (
  id INT AUTO_INCREMENT PRIMARY KEY,
  world_id INT NOT NULL,
  name VARCHAR(120) NOT NULL,
  description VARCHAR(500) NOT NULL DEFAULT '',
  backdrop VARCHAR(16) NOT NULL DEFAULT '🏞️',
  sort_order INT NOT NULL DEFAULT 0,
  FOREIGN KEY (world_id) REFERENCES worlds(id) ON DELETE CASCADE
) CHARACTER SET utf8mb4;

CREATE TABLE IF NOT EXISTS scene_items (
  id INT AUTO_INCREMENT PRIMARY KEY,
  scene_id INT NOT NULL,
  kind ENUM('npc','object') NOT NULL DEFAULT 'npc',
  name VARCHAR(80) NOT NULL,
  emoji VARCHAR(16) NOT NULL DEFAULT '🙂',
  line VARCHAR(300) NOT NULL DEFAULT '',
  sort_order INT NOT NULL DEFAULT 0,
  FOREIGN KEY (scene_id) REFERENCES scenes(id) ON DELETE CASCADE
) CHARACTER SET utf8mb4;

CREATE TABLE IF NOT EXISTS situations (
  id INT AUTO_INCREMENT PRIMARY KEY,
  scene_id INT NOT NULL,
  item_id INT NULL,
  vocabulary_id INT NOT NULL,
  context VARCHAR(600) NOT NULL,
  question VARCHAR(300) NOT NULL,
  explanation VARCHAR(500) NOT NULL DEFAULT '',
  hint VARCHAR(300) NOT NULL DEFAULT '',
  sort_order INT NOT NULL DEFAULT 0,
  FOREIGN KEY (scene_id) REFERENCES scenes(id) ON DELETE CASCADE,
  FOREIGN KEY (item_id) REFERENCES scene_items(id) ON DELETE SET NULL,
  FOREIGN KEY (vocabulary_id) REFERENCES vocabulary(id) ON DELETE CASCADE
) CHARACTER SET utf8mb4;

CREATE TABLE IF NOT EXISTS situation_options (
  id INT AUTO_INCREMENT PRIMARY KEY,
  situation_id INT NOT NULL,
  text VARCHAR(300) NOT NULL,
  is_correct TINYINT(1) NOT NULL DEFAULT 0,
  sort_order INT NOT NULL DEFAULT 0,
  FOREIGN KEY (situation_id) REFERENCES situations(id) ON DELETE CASCADE
) CHARACTER SET utf8mb4;

CREATE TABLE IF NOT EXISTS encounters (
  player_id CHAR(36) NOT NULL,
  word_key VARCHAR(80) NOT NULL,
  first_world_id INT NULL,
  first_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  uses INT NOT NULL DEFAULT 1,
  PRIMARY KEY (player_id, word_key)
) CHARACTER SET utf8mb4;

CREATE TABLE IF NOT EXISTS solved (
  player_id CHAR(36) NOT NULL,
  situation_id INT NOT NULL,
  was_new TINYINT(1) NOT NULL DEFAULT 0,
  was_reused TINYINT(1) NOT NULL DEFAULT 0,
  solved_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (player_id, situation_id),
  FOREIGN KEY (situation_id) REFERENCES situations(id) ON DELETE CASCADE
) CHARACTER SET utf8mb4;

CREATE TABLE IF NOT EXISTS seed_log (
  seed_key VARCHAR(160) NOT NULL PRIMARY KEY,
  applied_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) CHARACTER SET utf8mb4
